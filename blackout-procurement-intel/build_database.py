def tier(score, hard_gate):
    if hard_gate:
        return "NO-GO"
    if score >= 4.2:
        return "S"
    if score >= 3.7:
        return "A"
    if score >= 3.2:
        return "B"
    if score >= 2.6:
        return "C"
    return "NO-GO"


