def main():
    out = []
    for raw in OPPORTUNITIES:
        row = {k: v for k, v in raw.items() if k not in FACTOR_FIELDS.values()}
        factor = {k: raw[f] for k, f in FACTOR_FIELDS.items()}
        row["weighted_score"] = round(sum(WEIGHTS[k] * v for k, v in factor.items()), 2)
        row["tier"] = tier(row["weighted_score"], raw.get("hard_gate"))
        row.update({f"score_{k}": v for k, v in factor.items()})
        out.append(row)

    out.sort(key=lambda r: (r["tier"] == "NO-GO", -r["weighted_score"]))
    path = Path(__file__).with_name("database.csv")
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(out[0].keys()))
        w.writeheader()
        w.writerows(out)
    for r in out:
        print(f'{r["id"]}  {r["tier"]:6} {r["weighted_score"]:.2f}  {r["opportunity"][:72]}')


if __name__ == "__main__":
    main()
